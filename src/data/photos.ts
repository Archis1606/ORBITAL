export function getPhoto(id: string) {
  return photos.find((photo) => photo.id === id)
}

export function photosByDiscipline(discipline: Discipline) {
  return photos.filter((photo) => photo.discipline === discipline)
}

export function featuredPhotos() {
  return photos.filter((photo) => photo.featured)
}

export function photoCreator(photo: Photo) {
  return getCreator(photo.creatorId)
}
